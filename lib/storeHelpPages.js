export function isHelpHowToQuestion(question = '') {
  const text = String(question || '');
  if ((/how many|how much|units sold|revenue|\bsales i got\b|\borders i got\b/i.test(text)) && !/\bpages?\b/i.test(text)) return false;
  if (/\b(?:last|past|previous)\s+\d+\s+(?:month|week|day)/i.test(text) && /sales|order|report|download/i.test(text)) {
    return false;
  }
  if (/(down|excel|pdf|export)/.test(text) && /(sale|order|report|customer|revenue|deliver|detail)/.test(text)) return false;
  if (/\b\d{4,8}\b/.test(text) && /order/i.test(text)) return false;
  return /how (can|do|to)|where (is|do|can|to)|which page|change|edit|update|upload|replace|navigate|go to|what is|tell me about|explain|open the|take me to|show me the page/i.test(text);
}

function escapeHelpRegex(value = '') {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

export function normalizeHelpMatchText(value = '') {
  const typos = {
    navabr: 'navbar',
    navber: 'navbar',
    nabvar: 'navbar',
    baner: 'banner',
    bannr: 'banner',
    coupn: 'coupon',
    cupon: 'coupon',
    popop: 'popup',
    popoup: 'popup',
    hompage: 'homepage',
    categroy: 'category',
    catagory: 'category',
    footre: 'footer',
    shiping: 'shipping',
    disount: 'discount',
    dicount: 'discount',
  };
  return String(value || '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .split(' ')
    .filter(Boolean)
    .map((word) => typos[word] || word)
    .join(' ');
}

export function helpTextHasPhrase(text = '', phrase = '') {
  const hay = ` ${normalizeHelpMatchText(text)} `;
  const words = normalizeHelpMatchText(phrase).split(' ').filter(Boolean);
  if (!words.length || hay.trim().length === 0) return false;
  const filler = '(?:\\s+(?:the|a|an|my|our|this|that|to|of|for|in|on|your))?';
  const parts = words.map((word, index) => {
    const token = word.length >= 4 && !word.endsWith('s')
      ? `${escapeHelpRegex(word)}s?`
      : escapeHelpRegex(word);
    return index === 0 ? token : `${filler}\\s+${token}`;
  });
  return new RegExp(` ${parts.join('')} `).test(hay);
}

const APP_GENERIC_KEYWORDS = new Set([
  'navbar', 'footer', 'offers', 'offer', 'coupon', 'coupons',
  'banner', 'banners', 'slider', 'sliders', 'logo', 'header',
]);

function scoreHelpPage(page, text) {
  const matched = (page.keywords || []).filter((keyword) => helpTextHasPhrase(text, keyword));
  let score = matched.reduce((sum, keyword) => sum + keyword.length, 0);
  let specificity = matched.reduce((max, keyword) => Math.max(max, normalizeHelpMatchText(keyword).length), 0);
  const label = String(page.label || '').toLowerCase();
  if (label && helpTextHasPhrase(text, label)) {
    score += label.length + 4;
    specificity = Math.max(specificity, normalizeHelpMatchText(label).length);
  }
  if (!score) return { score: 0, specificity: 0 };

  const asksApp = /\b(app|mobile|phone|flutter)\b/.test(text);
  const isAppPage = String(page.href || '').includes('/mobile-features');
  const onlyGeneric = matched.every((keyword) => APP_GENERIC_KEYWORDS.has(normalizeHelpMatchText(keyword)));
  if (isAppPage && !asksApp && onlyGeneric) return { score: 0, specificity: 0 };
  if (!isAppPage && asksApp) score = Math.max(1, Math.floor(score / 2));
  if (isAppPage && asksApp) score += 6;
  return { score, specificity };
}

export function matchHelpHowTo(question = '') {
  const text = normalizeHelpMatchText(question);
  if (!text) return null;
  if ((/how many|how much|units sold|revenue|\bsales i got\b|\borders i got\b/i.test(text)) && !/\bpages?\b/i.test(text)) return null;
  if (/\b(?:last|past|previous)\s+\d+\s+(?:month|week|day)/i.test(text) && /sales|order|report|download/i.test(text)) {
    return null;
  }
  if (/(down|excel|pdf|export)/.test(text) && /(sale|order|report|customer|revenue|deliver|detail)/.test(text)) return null;
  if (/\b\d{4,8}\b/.test(text) && /order/i.test(text)) return null;
  if (/\bauthor\b/.test(text)) return null;

  let best = null;
  for (const page of STORE_HELP_PAGES) {
    const ranked = scoreHelpPage(page, text);
    const moreSpecificAppPage = ranked.score > 0
      && ranked.specificity === best?.specificity
      && ranked.score === best?.score
      && String(page.href || '').includes('/mobile-features')
      && String(best?.href || '').includes('/mobile-features')
      && String(page.href || '').length > String(best?.href || '').length;
    const better = !best
      || ranked.specificity > best.specificity
      || (ranked.specificity === best.specificity && ranked.score > best.score)
      || moreSpecificAppPage;
    if (better && ranked.score > 0) best = { ...page, ...ranked };
  }

  const minScore = isHelpHowToQuestion(question) ? 4 : 6;
  if (!best || best.score < minScore) return null;
  return {
    href: best.href,
    label: best.label,
    answer: best.answer,
  };
}

